/**
 * Scorex Overlay Engine V2 (HYBRID ARCHITECTURE)
 * The "Canvas": Passively listens to the Backend Brain for triggers.
 * CRASH-PREVENTION: Ultra-lightweight, zero heavy interval loops.
 */
(function () {
  'use strict';

  const config = window.OVERLAY_CONFIG || {};
  const matchId = config.matchId;
  const apiBaseUrl = config.apiBaseUrl || 'https://scorex-backend.onrender.com/api/v1';
  const socketUrl = apiBaseUrl.replace('/api/v1', '');

  // Master Configuration for timings (Can be injected from DB later)
  const overlaySettings = config.config || {
    startupSequence: { showVsScreenDuration: 8, showTossDuration: 6 }
  };

  let matchData = null;
  let socket = null;
  
  // State Machine: BOOTING -> VS_SCREEN -> TOSS -> LIVE
  let currentState = 'BOOTING'; 

  window.ScorexOverlay = {
    getData: () => matchData,
    refresh: () => safeFetchMatchData()
  };

  // 🛡️ SAFE FETCH
  async function safeFetchMatchData() {
    if (!matchId) return safeUpdateState(getDemoData());
    try {
      const res = await fetch(`${apiBaseUrl}/matches/${matchId}`, { headers: { 'Accept': 'application/json' } });
      if (!res.ok) throw new Error(`HTTP ${res.status}`);
      const json = await res.json();
      safeUpdateState(json.data || json);
    } catch (err) {
      console.error('[Scorex Engine] Fetch failed:', err);
      safeUpdateState(getDemoData());
    }
  }

  // 🛡️ SAFE SOCKET
  function safeConnectSocket() {
    if (typeof io === 'undefined') return console.error('[Scorex Engine] Socket.io missing');
    socket = io(socketUrl, { transports: ['websocket', 'polling'] });
    socket.on('connect', () => { if (matchId) socket.emit('joinMatch', matchId); });
    socket.on('scoreUpdate', (data) => safeUpdateState(data));
    socket.on('matchEnded', (data) => safeUpdateState(data));
  }

  // 🧠 THE STATE MACHINE & TRIGGER DISPATCHER
  function safeUpdateState(rawDoc) {
    try {
      if (!rawDoc) return;

      // Extract the trigger generated by the backend
      const trigger = rawDoc.activeTrigger || null;
      
      // Normalize raw mongoose doc into flat UI data
      const rawMatch = rawDoc.match || rawDoc;
      let flatData = typeof window.normalizeScoreData === 'function' 
        ? window.normalizeScoreData(rawMatch) 
        : rawMatch;

      matchData = flatData;

      // --- 1. STARTUP SEQUENCE LOGIC ---
      const isMatchNew = flatData.team1Score === 0 && flatData.team1Overs === "0.0" && flatData.team1Wickets === 0;

      if (currentState === 'BOOTING') {
        if (isMatchNew && rawMatch.team1Name) {
          currentState = 'VS_SCREEN';
          dispatchTrigger({ type: 'SHOW_VS_SCREEN', duration: overlaySettings.startupSequence.showVsScreenDuration });
          
          setTimeout(() => {
            if (rawMatch.tossWinnerName) {
              currentState = 'TOSS';
              dispatchTrigger({ type: 'SHOW_TOSS', duration: overlaySettings.startupSequence.showTossDuration });
              
              setTimeout(() => {
                currentState = 'LIVE';
                dispatchTrigger({ type: 'SHOW_SCOREBOARD' });
              }, overlaySettings.startupSequence.showTossDuration * 1000);
            } else {
              currentState = 'LIVE';
              dispatchTrigger({ type: 'SHOW_SCOREBOARD' });
            }
          }, overlaySettings.startupSequence.showVsScreenDuration * 1000);
        } else {
          // Match is already in progress, skip straight to live scoreboard
          currentState = 'LIVE';
          dispatchTrigger({ type: 'SHOW_SCOREBOARD' });
        }
      }

      // --- 2. LIVE GAME TRIGGERS (From Backend) ---
      if (currentState === 'LIVE' && trigger) {
        dispatchTrigger(trigger);
      }

      // ALWAYS Update the base score text
      window.postMessage({ type: 'UPDATE_SCORE', data: flatData, raw: rawMatch }, '*');

    } catch (err) {
      console.error('[Scorex Engine] State update error:', err);
    }
  }

  function dispatchTrigger(triggerObj) {
    console.log(`[Scorex Engine] 🎬 Firing Animation: ${triggerObj.type}`, triggerObj);
    window.postMessage({ type: 'OVERLAY_TRIGGER', payload: triggerObj }, '*');
  }

  // FALLBACK DEMO DATA (Simplified for brevity)
  function getDemoData() {
    return {
      match: { tossWinnerName: 'Team A', tossDecision: 'bat' },
      team1Score: 0, team1Wickets: 0, team1Overs: '0.0',
      team1Name: 'PREMIUM BATS', team2Name: 'ROYAL CHALLENGERS'
    };
  }

  function init() {
    const urlParams = new URLSearchParams(window.location.search);
    if (urlParams.get('preview') === 'true') {
      safeUpdateState(getDemoData()); return;
    }
    safeFetchMatchData();
    safeConnectSocket();
  }

  if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', init);
  else init();

})();