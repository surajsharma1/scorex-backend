import express from 'express';
import { protect } from '../middleware/auth';
import * as mc from '../controllers/matchController';
const router = express.Router();
router.get('/', mc.getMatches);
router.get('/live', mc.getLiveMatches);
router.get('/:id', mc.getMatch);
router.post('/', protect, mc.createMatch);
router.put('/:id', protect, mc.updateMatch);
router.delete('/:id', protect, mc.deleteMatch);
import { protectScorer } from '../middleware/scorerAuth';

router.post('/:id/start', protect, protectScorer, mc.startMatch);
router.post('/:id/select-players', protect, protectScorer, mc.selectPlayers);
router.post('/:id/score', protect, protectScorer, mc.addBall);
router.post('/:id/undo', protect, protectScorer, mc.undoLastBall);
router.post('/:id/end-innings', protect, protectScorer, mc.endInnings);
router.post('/:id/end', protect, protectScorer, mc.endMatch);
router.put('/:id/status', protect, protectScorer, mc.updateMatchStatus);
export default router;
